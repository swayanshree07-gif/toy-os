#!/usr/bin/env python3
"""Convert tools/font.txt (5x8 pixel-art glyphs) into a C array.

Output: const uint8_t font5x8[95][8] for ASCII 0x20..0x7E; each byte is a row,
bit 4 = leftmost pixel. Missing glyphs are rendered as a hollow box.
"""
import sys

def main(src, dst):
    glyphs = {}
    with open(src, encoding="ascii") as f:
        for lineno, line in enumerate(f, 1):
            line = line.rstrip("\n")
            if len(line) < 2 or line[1] != "|":
                continue
            ch, rows = line[0], line[2:].split()
            if len(rows) > 8:
                sys.exit(f"{src}:{lineno}: glyph {ch!r} has {len(rows)} rows (max 8)")
            bits = []
            for r in rows:
                if len(r) != 5 or set(r) - {"#", "."}:
                    sys.exit(f"{src}:{lineno}: bad row {r!r} in glyph {ch!r}")
                bits.append(int(r.replace("#", "1").replace(".", "0"), 2))
            bits += [0] * (8 - len(bits))
            if ch in glyphs:
                sys.exit(f"{src}:{lineno}: duplicate glyph {ch!r}")
            glyphs[ch] = bits
    box = [0x1F, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1F, 0]
    missing = [chr(c) for c in range(0x20, 0x7F) if chr(c) not in glyphs]
    if missing:
        print(f"mkfont: warning: missing glyphs {''.join(missing)!r}", file=sys.stderr)
    with open(dst, "w", encoding="ascii") as out:
        out.write("/* Generated by tools/mkfont.py from tools/font.txt. Do not edit. */\n")
        out.write("#include <stdint.h>\n\nconst uint8_t font5x8[95][8] = {\n")
        for c in range(0x20, 0x7F):
            b = glyphs.get(chr(c), box)
            esc = chr(c) if chr(c) not in "\\*/" else " "
            out.write("    {" + ", ".join(f"0x{x:02x}" for x in b) + f"}}, /* '{esc}' */\n")
        out.write("};\n")

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
