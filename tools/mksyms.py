#!/usr/bin/env python3
"""Generate the kernel symbol table (C source) from `nm -n` output on stdin.

Only code symbols (t/T) inside [__text_start, __text_end) are kept, sorted by address.
With no input (first link pass) an empty table is produced. The kernel is linked twice:
pass 1 with the empty table, pass 2 with the real one. The table lives in .rodata, after
.text, so code addresses are identical in both passes (the Makefile checks this)."""
import sys

syms, text_start, text_end = [], None, None
for line in sys.stdin:
    parts = line.split()
    if len(parts) != 3:
        continue
    addr, kind, name = int(parts[0], 16), parts[1], parts[2]
    if name == "__text_start":
        text_start = addr
    elif name == "__text_end":
        text_end = addr
    elif kind in "tT" and not name.startswith("__") and not name.startswith(".L"):
        syms.append((addr, name))

if text_start is not None and text_end is not None:
    syms = [s for s in syms if text_start <= s[0] < text_end]
syms.sort()
# one name per address (first wins)
uniq = []
for a, n in syms:
    if not uniq or uniq[-1][0] != a:
        uniq.append((a, n))

out = sys.stdout
out.write("/* generated by tools/mksyms.py - do not edit */\n#include \"ksyms.h\"\n")
out.write("const struct ksym ksyms[] = {\n")
for a, n in uniq:
    out.write(f"    {{ 0x{a:016x}ull, \"{n}\" }},\n")
if not uniq:
    out.write("    { 0, \"\" },\n")
out.write("};\n")
out.write(f"const unsigned ksyms_count = {len(uniq)};\n")
